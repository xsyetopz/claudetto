// The ignore files ride the setup command's dialog, so they take no model turn either.

import type { On } from "claude-code";
import { type Engine, expect, test } from "claude-code/testing";
import { questionOf, run } from "./support.ts";

const FILE = "/home/u/.claude/settings.json";
const QUESTION = "Write the ignore file block?";

interface Lab {
	readonly disk: Map<string, string>;
	readonly asked: string[];
	readonly written: string[];
}

/** A repo at `/r` that holds `files` and the `held` texts, a settings file that already holds every key, and an `answer`. */
const lab = (
	on: On,
	files: readonly string[],
	held: Readonly<Record<string, string>>,
	answer: string,
	inRepo = true,
): Lab => {
	const state: Lab = {
		disk: new Map(
			Object.entries(held).map(([name, text]) => [`/r/${name}`, text]),
		),
		asked: [],
		written: [],
	};
	on("session.cwd", () => ({ value: "/r" }));
	on("env.get", (_$, e) => ({
		value: e.name === "HOME" ? "/home/u" : undefined,
	}));
	on("fs.exists", (_$, e) => ({
		value: e.path === FILE || state.disk.has(e.path),
	}));
	on("fs.read", (_$, e) => {
		if (e.path === FILE) {
			return { value: "{}" };
		}
		const text = state.disk.get(e.path);
		if (text === undefined) {
			throw new Error("no file");
		}
		return { value: text };
	});
	on("fs.write", (_$, e) => {
		state.disk.set(e.path, e.text);
		state.written.push(e.path);
		return { value: undefined };
	});
	on("process.run", (_$, e) => {
		const line = e.argv.join(" ");
		const revParse = line.includes("rev-parse");
		let stdout = files.join("\n");
		if (line.startsWith("uname")) {
			stdout = "Darwin\n";
		} else if (revParse) {
			stdout = "true\n";
		}
		const failed = revParse && !inRepo;
		return {
			value: {
				stdout: failed ? "" : stdout,
				stderr: "",
				exitCode: failed ? 128 : 0,
				isStdoutTruncated: false,
				isStderrTruncated: false,
			},
		};
	});
	on("tool.call", (_$, e, next) => {
		if (e.tool !== "AskUserQuestion") {
			return next(e);
		}
		const question = questionOf(e);
		state.asked.push(question);
		return {
			result: {
				answers: { [question]: question.includes(QUESTION) ? answer : "Skip" },
			},
		};
	});
	return state;
};

const GO = ["go.mod", "main.go"];

test("a Write puts the block after the user's lines and keeps them", async ($: Engine, on: On) => {
	const state = lab(
		on,
		GO,
		{
			".gitignore": `mine
!Thumbs.db
`,
		},
		"Write",
	);

	const text = await run($);

	const gitignore = state.disk.get("/r/.gitignore") ?? "";
	expect(
		gitignore.startsWith(
			`mine
!Thumbs.db

# >>> claudetto: generated by /claudetto:setup, edit outside this block
`,
		),
	).toBe(true);
	expect(gitignore).toContain("\nvendor/\n");
	expect(gitignore).not.toContain("\nThumbs.db\n");
	expect(gitignore.endsWith("# <<< claudetto\n")).toBe(true);
	expect(text).toContain("Wrote `/r/.gitignore`.");
});

test("the dialog shows the diff of the file", async ($: Engine, on: On) => {
	const state = lab(on, GO, {}, "Skip");

	await run($);

	const asked = state.asked.find((q) => q.includes(QUESTION)) ?? "";
	expect(asked).toContain("+++ .gitignore");
	expect(asked).toContain("+.DS_Store");
});

test("a Skip writes no ignore file", async ($: Engine, on: On) => {
	const state = lab(on, GO, {}, "Skip");

	const text = await run($);

	expect(state.disk.has("/r/.gitignore")).toBe(false);
	expect(text).toContain("Wrote no ignore file.");
});

test("a settled repo is asked nothing, and a rerun changes no byte", async ($: Engine, on: On) => {
	const first = lab(on, GO, {}, "Write");
	await run($);
	const settled = first.disk.get("/r/.gitignore") ?? "";
	expect(settled).not.toBe("");
	first.asked.length = 0;
	first.written.length = 0;

	await run($);

	expect(first.asked.some((q) => q.includes(QUESTION))).toBe(false);
	expect(first.written).toEqual([]);
	expect(first.disk.get("/r/.gitignore")).toBe(settled);
});

test("a repo with an AGENTS.md is still offered the ignore files", async ($: Engine, on: On) => {
	const state = lab(on, GO, { "AGENTS.md": "mine\n" }, "Skip");

	await run($);

	expect(state.asked.some((q) => q.includes(QUESTION))).toBe(true);
});

test("a folder that is not a git repo is offered nothing", async ($: Engine, on: On) => {
	const state = lab(on, GO, {}, "Write", false);

	await run($);

	expect(state.asked.some((q) => q.includes(QUESTION))).toBe(false);
});
