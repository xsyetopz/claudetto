// Writes the generated rules as several TypeScript modules, so no module passes the repo's file-length limit.
// A hooks module can import only code files, so the data is code and not JSON.
import { mkdir, readdir, rm } from "node:fs/promises";

import { spawn, write } from "bun";

const BODY_LINES_MAX = 280;
const IMPORTS_MAX = 8;
const INLINE_MAX = 60;
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/u;
const HEADER = "// Generated by scripts/vendor-rules.ts; do not edit.";

const hasControl = (text: string): boolean => {
	for (const c of text) {
		if ((c.codePointAt(0) ?? 0) < 32) {
			return true;
		}
	}
	return false;
};

/** A string literal that holds `text` and that the repo's lint accepts: `String.raw` for backslashes, an escaped template for `${`. */
const literal = (text: string): string => {
	const plain =
		!hasControl(text) && !text.includes("`") && !text.endsWith("\\");
	if (text.includes("${")) {
		return `\`${text.replaceAll(/[\\`]|\$\{/gu, (found) => `\\${found}`)}\``;
	}
	if (text.includes("\\") && plain) {
		return `String.raw\`${text}\``;
	}
	return JSON.stringify(text);
};

const render = (value: unknown, depth: number): string => {
	const pad = "\t".repeat(depth + 1);
	const close = "\t".repeat(depth);
	if (typeof value === "string") {
		return literal(value);
	}
	if (Array.isArray(value)) {
		if (value.length === 0) {
			return "[]";
		}
		const inline = `[${value.map((v) => render(v, depth)).join(", ")}]`;
		if (
			value.every((v) => typeof v === "string") &&
			inline.length <= INLINE_MAX
		) {
			return inline;
		}
		return `[\n${value.map((v) => `${pad}${render(v, depth + 1)},\n`).join("")}${close}]`;
	}
	if (typeof value === "object" && value !== null) {
		const rows = Object.entries(value).map(([key, v]) => {
			const name = IDENTIFIER.test(key) ? key : JSON.stringify(key);
			return `${pad}${name}: ${render(v, depth + 1)},\n`;
		});
		return `{\n${rows.join("")}${close}}`;
	}
	return JSON.stringify(value);
};

const ITEM_MARK = "\t// item";

/** `source` as `bun fmt` prints it, so a generated module is the same before and after the repo's format check. */
const formatted = async (source: string): Promise<string> => {
	const run = spawn(["bun", "fmt", "--stdin-filepath", "x.ts"], {
		// The formatter reads its indent from the `.editorconfig` above its working folder.
		cwd: new URL("..", import.meta.url).pathname,
		stdin: Buffer.from(source),
		stdout: "pipe",
		stderr: "pipe",
	});
	const [out, err, code] = await Promise.all([
		new Response(run.stdout).text(),
		new Response(run.stderr).text(),
		run.exited,
	]);
	if (code !== 0) {
		throw new Error(`bun fmt failed: ${err}`);
	}
	return out;
};

/** Each item as `bun fmt` prints it, since the formatter wraps long rows and so adds lines that the length limit counts. */
const formattedItems = async (items: readonly unknown[]): Promise<string[]> => {
	const source = `export const X = [\n${items.map((item) => `${ITEM_MARK}\n\t${render(item, 1)},`).join("\n")}\n];\n`;
	const printed = await formatted(source);
	const texts = printed
		.split("\n")
		.slice(1, -2)
		.join("\n")
		.split(`${ITEM_MARK}\n`)
		.slice(1)
		.map((text) => text.trimEnd());
	if (texts.length !== items.length) {
		throw new Error(
			`bun fmt kept ${texts.length} of ${items.length} items; check the .editorconfig indent`,
		);
	}
	return texts;
};

/** Fills modules of at most `BODY_LINES_MAX` formatted item lines, in order. */
const chunksOf = async (items: readonly unknown[]): Promise<string[][]> => {
	const chunks: string[][] = [];
	let lines = 0;
	for (const text of await formattedItems(items)) {
		const count = text.split("\n").length;
		const last = chunks.at(-1);
		if (last === undefined || lines + count > BODY_LINES_MAX) {
			chunks.push([text]);
			lines = count;
		} else {
			last.push(text);
			lines += count;
		}
	}
	return chunks;
};

interface Part {
	file: string;
	id: string;
}

const partOf = (kind: string, index: number, tag: string): Part => {
	const number = String(index + 1).padStart(2, "0");
	const label = tag === "" ? kind : `${kind}-${tag}`;
	return {
		file: `${label}-${number}`,
		id: `${label.toUpperCase().replace("-", "_")}_${number}`,
	};
};

const importLines = (parts: readonly Part[], base: string): string =>
	parts.map((p) => `import { ${p.id} } from "${base}${p.file}.ts";`).join("\n");

const joinedText = (joined: Part, members: readonly Part[]): string =>
	`${HEADER}\n${importLines(members, "./")}\n\nexport const ${joined.id} = [${members.map((m) => `...${m.id}`).join(", ")}] as const;\n`;

interface Module {
	name: string;
	text: string;
}

/** The modules of one kind, and the parts the index imports: a long list goes through group modules, so no module imports more than `IMPORTS_MAX`. */
const planKind = async (
	kind: string,
	items: readonly unknown[],
): Promise<{ top: Part[]; modules: Module[] }> => {
	const chunks = await chunksOf(items);
	const held = chunks.map((chunk, index) => ({
		part: partOf(kind, index, ""),
		chunk,
	}));
	const parts = held.map((h) => h.part);
	const modules = held.map(({ part, chunk }) => ({
		name: part.file,
		text: `${HEADER}\nexport const ${part.id} = [\n${chunk.join("\n")}\n] as const;\n`,
	}));
	const count = Math.ceil(parts.length / IMPORTS_MAX);
	if (count <= 1) {
		return { top: parts, modules };
	}
	const groups = Array.from({ length: count }, (_, group) => ({
		joined: partOf(kind, group, "group"),
		members: parts.slice(group * IMPORTS_MAX, (group + 1) * IMPORTS_MAX),
	}));
	return {
		top: groups.map((g) => g.joined),
		modules: [
			...modules,
			...groups.map((g) => ({
				name: g.joined.file,
				text: joinedText(g.joined, g.members),
			})),
		],
	};
};

/** Replaces the generated modules under `gate` with `data`: an index, `rules.generated/rules-NN.ts`, and `rules.generated/fixtures-NN.ts`. */
export const writeGenerated = async (
	gate: URL,
	data: {
		source: string;
		commit: string;
		sha256: string;
		license: string;
		rules: readonly unknown[];
		fixtures: readonly unknown[];
	},
): Promise<void> => {
	const folder = new URL("rules.generated/", gate);
	await rm(folder, { recursive: true, force: true });
	await mkdir(folder, { recursive: true });
	const [rules, fixtures] = await Promise.all([
		planKind("rules", data.rules),
		planKind("fixtures", data.fixtures),
	]);
	const plans = { rules, fixtures };
	await Promise.all(
		[...rules.modules, ...fixtures.modules].map(async (m) =>
			write(new URL(`${m.name}.ts`, folder), await formatted(m.text)),
		),
	);
	const imports = importLines(
		// Sorted by path, as the import lint wants: `fixtures` before `rules`, and each list is numbered in order.
		[...plans.fixtures.top, ...plans.rules.top],
		"./rules.generated/",
	);
	const spread = (kind: "rules" | "fixtures"): string =>
		plans[kind].top.map((p) => `...${p.id}`).join(", ");
	await write(
		new URL("rules.generated.ts", gate),
		await formatted(
			`// Generated by scripts/vendor-rules.ts from rules.patch.json and ${data.source}; do not edit.\n${imports}\n\nexport const GENERATED = {\n\tsource: ${literal(data.source)},\n\tcommit: ${literal(data.commit)},\n\tsha256: ${literal(data.sha256)},\n\tlicense: ${literal(data.license)},\n\trules: [${spread("rules")}],\n\tfixtures: [${spread("fixtures")}],\n} as const;\n`,
		),
	);
	const names = await readdir(folder);
	console.info(`wrote ${names.length} generated modules`);
};
