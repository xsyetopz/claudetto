// The tree has no wiki. It is the code and the recipes; `archive/`, `docs/`, and
// `openspec/` are prose and evidence, and the word may appear there.

import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { file as bunFile, Glob } from "bun";

const ROOT = join(import.meta.dir, "..", "..");

/** The code and the manifests of the new tree, which no wiki path may appear in. */
const CODE_GLOBS = [
	"plugins/**/*.ts",
	"plugins/**/*.tsx",
	"plugins/**/*.json",
	"claudekit/**/*.ts",
	"tools/**/*.ts",
	"tests/**/*.ts",
	".github/workflows/*.yml",
];

const WIKI = /wiki/i;

/** A recipe that builds a page, which the gate of the new tree has none of. */
const GENERATE = /\bgenerate\b/i;

/**
 * The files the scan skips, and why each one is not this tree's code.
 *
 * This file names the word in order to forbid it. The Gitleaks rules are data of the Gitleaks
 * project, generated by `just gitleaks-rules` and never written by hand: the word appears in the
 * stopword list of its `generic-api-key` rule, which names `wiki` and `mediawiki` among some 1,500
 * common words that must not count as a secret.
 */
const SKIPPED = new Set([
	"tests/repo/no-wiki.test.ts",
	"plugins/claudetto/src/secrets/gitleaks/rules.ts",
]);

/** The paths that `globs` match under `ROOT`, sorted. */
const pathsOf = async (globs: string[]): Promise<string[]> => {
	const scans = await Promise.all(
		globs.map(async (glob) => {
			const found: string[] = [];
			for await (const path of new Glob(glob).scan(ROOT)) {
				found.push(path);
			}
			return found;
		}),
	);
	return [...new Set(scans.flat())]
		.filter((path) => !SKIPPED.has(path))
		.sort((a, b) => a.localeCompare(b));
};

/** The `file:line` of every line of `paths` that matches `WIKI`. */
const wikiLines = async (paths: string[]): Promise<string[]> => {
	const hits = await Promise.all(
		paths.map(async (path) => {
			const text = await bunFile(join(ROOT, path)).text();
			return text
				.split("\n")
				.flatMap((line, i) => (WIKI.test(line) ? [`${path}:${i + 1}`] : []));
		}),
	);
	return hits.flat();
};

describe("the new tree holds no wiki", () => {
	test("no code file and no workflow names a wiki", async () => {
		const paths = await pathsOf(CODE_GLOBS);

		const hits = await wikiLines(paths);

		expect(paths.length).toBeGreaterThan(0);
		expect(hits).toEqual([]);
	});

	test("the recipes name no wiki step and no generated-page step", async () => {
		const text = await bunFile(join(ROOT, "justfile")).text();

		const hits = text
			.split("\n")
			.flatMap((line, i) =>
				WIKI.test(line) || GENERATE.test(line) ? [`justfile:${i + 1}`] : [],
			);

		expect(hits).toEqual([]);
	});
});
