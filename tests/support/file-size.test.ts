// The line bound of each file is checked by `just validate` (`tools/validate.ts`).
// These tests pin the rule of `overBound` at its boundaries (the "Bounds" section of `spec/changes/1.0.0/design.md`).

import { expect, test } from "bun:test";
import fs from "node:fs";
import path from "node:path";
import { FILE_MAX_LINES, TEST_FILE_MAX_LINES } from "../../tools/limits.ts";
import { overBound } from "../../tools/validate.ts";
import { tmpDir } from "./repo.ts";

test("a file and a test file one line over the bound fail", async () => {
  const root = tmpDir("file-size");
  const write = (name: string, n: number) =>
    Bun.write(path.join(root, name), "x\n".repeat(n));
  await write("at.mjs", FILE_MAX_LINES);
  await write("over.mjs", FILE_MAX_LINES + 1);
  await write("at.test.mjs", TEST_FILE_MAX_LINES);
  await write("over.test.mjs", TEST_FILE_MAX_LINES + 1);
  fs.mkdirSync(path.join(root, "schemas"));
  await write("schemas/big.json", TEST_FILE_MAX_LINES + 1);
  const files = [
    "at.mjs",
    "over.mjs",
    "at.test.mjs",
    "over.test.mjs",
    "schemas/big.json",
  ];
  expect(await overBound(root, files)).toStrictEqual([
    `${FILE_MAX_LINES + 1} over.mjs`,
    `${TEST_FILE_MAX_LINES + 1} over.test.mjs`,
  ]);
});

test("Long generated file: a file with the header of `just generate` is out of the bound", async () => {
  const root = tmpDir("file-size-generated");
  const head = "<!-- Generated by `just generate` from `src/wiki/t.md`. -->\n";
  await Bun.write(path.join(root, "table.md"), head + "| x |\n".repeat(400));
  await Bun.write(path.join(root, "plain.md"), "| x |\n".repeat(400));
  expect(await overBound(root, ["table.md", "plain.md"])).toStrictEqual([
    "400 plain.md",
  ]);
});
