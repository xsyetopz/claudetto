// Behavior of `tools/generate/` (design D12): each text that a plugin ships comes from its source in `src/`.
// Each test that writes files works in its own folder under `TMPDIR`.

import { expect, test } from "bun:test";
import fs from "node:fs";
import path from "node:path";
import {
  isGenerated,
  outputs,
  stale,
  VALUES,
} from "../../tools/generate/emit/texts.ts";
import { REPO, tmpDir } from "./repo.ts";

/** A repository root with the files `files`, by path relative to the root. */
async function root(files: Record<string, string>): Promise<string> {
  const dir = tmpDir("generate");
  for (const [rel, text] of Object.entries(files))
    await Bun.write(path.join(dir, ...rel.split("/")), text);
  return dir;
}

/** Writes each generated file of `dir`, as `just generate` does. */
async function generate(dir: string): Promise<void> {
  for (const o of await outputs(dir))
    await Bun.write(path.join(dir, ...o.file.split("/")), o.text);
}

const AGENT = (name: string) =>
  `---\nname: ${name}\n---\n\n<rules>\n{{include rule}}\n</rules>\n`;

test("lint: each generated file of the repository matches its source", async () => {
  const found = await stale(REPO, await outputs(REPO));
  expect(found, found.join("\n")).toStrictEqual([]);
});

test("Generate: a changed shared rule reaches each agent body that repeats it", async () => {
  const dir = await root({
    "src/shared/rule.md": "Old rule.\n",
    "src/plugins/p/agents/a.md": AGENT("a"),
    "src/plugins/p/agents/b.md": AGENT("b"),
  });
  await Bun.write(path.join(dir, "src", "shared", "rule.md"), "New rule.\n");
  for (const o of await outputs(dir)) {
    expect(o.text).toContain("<rules>\nNew rule.\n</rules>");
    expect(o.text).not.toContain("Old rule.");
  }
});

test("a value of a limit fills its name, and an unknown name or part is an error that names the source", async () => {
  const [name, value] = Object.entries(VALUES)[0] as [string, string];
  const ok = await root({
    "src/plugins/p/x.md": `At most {{${name}}} words.\n`,
  });
  expect((await outputs(ok))[0]?.text).toContain(`At most ${value} words.`);
  const value404 = await root({ "src/plugins/p/x.md": "{{NO_SUCH_LIMIT}}\n" });
  await expect(outputs(value404)).rejects.toThrow(
    /src\/plugins\/p\/x\.md: no value/,
  );
  const part404 = await root({ "src/plugins/p/x.md": "{{include none}}\n" });
  await expect(outputs(part404)).rejects.toThrow(
    /src\/plugins\/p\/x\.md: no shared part/,
  );
});

test("Header: the first lines of each generated file that is not JSON name its source", async () => {
  for (const o of await outputs(REPO)) {
    if (o.file.endsWith(".json")) continue;
    const head = o.text.split("\n", 3).join("\n");
    expect(isGenerated(o.text), o.file).toBeTruthy();
    expect(head, o.file).toContain(`\`${o.source}\``);
  }
});

test("a header goes inside a frontmatter, as a comment before any other text, and in a `.ts` comment", async () => {
  const dir = await root({
    "src/plugins/p/a.md": "---\nname: a\n---\n\nBody.\n",
    "src/plugins/p/b.md": "Body.\n",
    "src/plugins/p/c.ts": "export const C = 1;\n",
  });
  const [a, b, c] = (await outputs(dir)).map((o) => o.text.split("\n"));
  expect(a?.[0]).toBe("---");
  expect(a?.[1]).toStartWith("# Generated by");
  expect(a?.[2]).toBe("name: a");
  expect(b?.[0]).toStartWith("<!-- Generated by");
  expect(c?.[0]).toStartWith("// Generated by");
});

test("Generated JSON file: a generated JSON file has no header and parses as its source", async () => {
  for (const o of await outputs(REPO)) {
    if (!o.file.endsWith(".json")) continue;
    expect(isGenerated(o.text), o.file).toBeFalsy();
    expect(Object.keys(JSON.parse(o.text)), o.file).not.toContain("$comment");
  }
});

// The Markdown, JSON, and text files under `plugins/` that the generator does not write, each with its reason.
const NOT_GENERATED: [RegExp, string][] = [
  [
    /^plugins\/[^/]+\/\.claude-plugin\/plugin\.json$/,
    "`just bump` writes the version, and `claude plugin validate --strict` refuses a header key",
  ],
  [
    /^plugins\/[^/]+\/tsconfig\.json$/,
    "Claude Code writes it when it is missing, and the type check reads it",
  ],
];
// The generated JSON files: JSON has no comment, so the list of the generator, and not a header, names their source.
const GENERATED_JSON = /^plugins\/[^/]+\/(?:hooks\/hooks|settings)\.json$/;

test("Text in the plugin: each Markdown, JSON, and text file under `plugins/` is generated or has a reason", async () => {
  const r = Bun.spawnSync(
    [
      "git",
      "ls-files",
      "--cached",
      "--others",
      "--exclude-standard",
      "plugins",
    ],
    { cwd: REPO },
  );
  const made = new Set((await outputs(REPO)).map((o) => o.file));
  const left: string[] = [];
  for (const file of r.stdout.toString().split("\n")) {
    if (
      !/\.(?:md|json|txt)$/.test(file) ||
      /^plugins\/[^/]+\/(?:tests|evals)\//.test(file)
    )
      continue;
    if (!fs.existsSync(path.join(REPO, file))) continue;
    if (NOT_GENERATED.some(([re]) => re.test(file))) continue;
    if (GENERATED_JSON.test(file) && made.has(file)) continue;
    if (!isGenerated(await Bun.file(path.join(REPO, file)).text()))
      left.push(file);
  }
  expect(left, left.join("\n")).toStrictEqual([]);
});

test("Edit by hand: the check names an edited generated file and its source, also for JSON", async () => {
  const dir = await root({
    "src/plugins/p/agents/a.md": "---\nname: a\n---\n\nBody.\n",
    "src/plugins/p/settings.json": "{}\n",
  });
  await generate(dir);
  expect(await stale(dir, await outputs(dir))).toStrictEqual([]);
  await Bun.write(path.join(dir, "plugins", "p", "agents", "a.md"), "edited\n");
  await Bun.write(path.join(dir, "plugins", "p", "settings.json"), '{"a":1}\n');
  const found = await stale(dir, await outputs(dir));
  expect(found).toHaveLength(2);
  expect(found[0]).toContain(
    "plugins/p/agents/a.md differs from its source src/plugins/p/agents/a.md",
  );
  expect(found[1]).toContain(
    "plugins/p/settings.json differs from its source src/plugins/p/settings.json",
  );
});

test("the check names a generated file whose source is gone", async () => {
  const dir = await root({ "src/plugins/p/a.md": "Body.\n" });
  await generate(dir);
  fs.rmSync(path.join(dir, "src", "plugins", "p", "a.md"));
  expect(await stale(dir, await outputs(dir))).toStrictEqual([
    "plugins/p/a.md has the header of a generated file, but no source in src/.",
  ]);
});

const HOOKS_SKELETON = (prompts: number) =>
  JSON.stringify({
    hooks: {
      Stop: [{ hooks: Array(prompts).fill({ type: "prompt", prompt: "old" }) }],
    },
  });

test("a `hooks.json` joins the lines of its description, keeps the newlines of its prompt, and ships no text file", async () => {
  const dir = await root({
    "src/plugins/p/hooks/hooks.json": HOOKS_SKELETON(1),
    "src/plugins/p/hooks/description.txt": "One.\nTwo.\n",
    "src/plugins/p/hooks/Stop.prompt.txt": "Line 1.\nLine 2.\n",
  });
  const made = await outputs(dir);
  expect(made.map((o) => o.file)).toStrictEqual(["plugins/p/hooks/hooks.json"]);
  const json = JSON.parse(made[0]?.text ?? "");
  expect(json.description).toBe("One. Two.");
  expect(json.hooks.Stop[0].hooks[0].prompt).toBe("Line 1.\nLine 2.");
});

test("a prompt file for an event with two `prompt` hooks is an error", async () => {
  const dir = await root({
    "src/plugins/p/hooks/hooks.json": HOOKS_SKELETON(2),
    "src/plugins/p/hooks/Stop.prompt.txt": "y\n",
  });
  await expect(outputs(dir)).rejects.toThrow(/2 prompt hooks/);
});
