// Writes `wiki/` from its source in `src/wiki/` (`just generate`).
//
//   bun tools/generate/index.ts           write each page
//   bun tools/generate/index.ts --check   exit 1 and name each page that differs from its source
//
// In a source, `{{NAME}}` gives the value of the limit `NAME` from the one place in `plugins/` where it is set,
// and a line `{{include snippet.json}}` or `{{include docs-snippet.json}}` gives a settings snippet of `plugins/claudetto/snippets.ts`.
// Each page starts with a header that names its source.

import fs from "node:fs";
import path from "node:path";
import {
  AUTOCOMPACT_PCT,
  CONTEXT_WINDOW,
  HAIKU_AUTOCOMPACT_WINDOW,
  HAIKU_HANDOFF_TRIGGER_TOKENS,
  HANDOFF_TRIGGER_TOKENS,
  MCP_DESCRIPTION_MAX_CHARS,
  USAGE_LEVELS,
} from "../../plugins/claudetto/kernel/budget.ts";
import { MAX_ROWS } from "../../plugins/claudetto/slices/statusline/limits.ts";
import { DOCS_SNIPPET, SNIPPET } from "../../plugins/claudetto/snippets.ts";

/** The words of the header, which a test finds in the first lines of a generated page. */
export const GENERATED_MARK = "Generated by `just generate` from";

/** The column bound of the formatter of Biome. */
const WIDTH = 80;

/** `json` as Biome formats it: two-space indents, and an array of scalars on one line when the line fits. */
export const formatJson = (json: unknown): string =>
  JSON.stringify(json, null, 2).replace(
    /^( *)("[^"]+": )\[\n((?: *(?:"(?:[^"\\]|\\.)*"|-?[\d.]+|true|false|null),?\n)+) *\]/gm,
    (all, indent: string, key: string, body: string) => {
      const items = body.split("\n").map((l) => l.trim().replace(/,$/, ""));
      const line = `${indent}${key}[${items.filter(Boolean).join(", ")}]`;
      return line.length <= WIDTH ? line : all;
    },
  );

/** The limits that a source can name as `{{NAME}}`. A number has the `300,000` form of the docs. */
export const VALUES: Record<string, string> = {
  ...Object.fromEntries(
    Object.entries({
      MCP_DESCRIPTION_MAX_CHARS,
      CONTEXT_WINDOW,
      HAIKU_AUTOCOMPACT_WINDOW,
      HAIKU_HANDOFF_TRIGGER_TOKENS,
      HANDOFF_TRIGGER_TOKENS,
      MAX_ROWS,
      USAGE_LEVEL_LOW: USAGE_LEVELS[0],
      USAGE_LEVEL_HIGH: USAGE_LEVELS[1],
    }).map(([name, value]) => [name, value.toLocaleString("en-US")]),
  ),
  // The percent keeps its 4 decimals, which `toLocaleString` would cut to 3.
  AUTOCOMPACT_PCT: String(AUTOCOMPACT_PCT),
};

const INCLUDES: Record<string, string> = {
  "snippet.json": formatJson(SNIPPET),
  "docs-snippet.json": formatJson(DOCS_SNIPPET),
};

const INCLUDE = /^\{\{include ([a-z0-9-]+\.json)\}\}$/gm;
const VALUE = /\{\{([A-Z0-9_]+)\}\}/g;

/** `text` of the source `source` with each include and value filled in. It throws on an unknown name. */
export const fill = (text: string, source: string): string =>
  text
    .replace(INCLUDE, (_m, name: string) => {
      const part = INCLUDES[name];
      if (part === undefined)
        throw new Error(`${source}: no include {{include ${name}}}`);
      return part;
    })
    .replace(VALUE, (_m, name: string) => {
      const value = VALUES[name];
      if (value === undefined)
        throw new Error(`${source}: no value {{${name}}}`);
      return value;
    });

/** `text` with the header that names `source`. A frontmatter starts the file, so the header goes inside it. */
const withHeader = (source: string, text: string): string => {
  const line = `${GENERATED_MARK} \`${source}\`. Edit the source and run \`just generate\`.`;
  return text.startsWith("---\n")
    ? `---\n# ${line}\n${text.slice(4)}`
    : `<!-- ${line} -->\n\n${text}`;
};

/** Each file under `dir`, relative to `dir`, with `/` separators, sorted. */
const walk = (dir: string): string[] =>
  fs
    .readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) =>
      path
        .relative(dir, path.join(e.parentPath, e.name))
        .split(path.sep)
        .join(path.posix.sep),
    )
    .sort();

/** Each page of `wiki/` in `root`, as its path and its text. */
export const pages = async (
  root: string,
): Promise<{ file: string; text: string }[]> =>
  Promise.all(
    walk(path.join(root, "src/wiki")).map(async (rel) => {
      const source = `src/wiki/${rel}`;
      const text = await Bun.file(path.join(root, source)).text();
      return {
        file: `wiki/${rel}`,
        text: rel.endsWith(".md")
          ? withHeader(source, fill(text, source))
          : text,
      };
    }),
  );

/** The messages for each page of `root` that differs from its source, and for each page of `wiki/` with no source. */
export const problems = async (root: string): Promise<string[]> => {
  const made = await pages(root);
  const found: string[] = [];
  for (const { file, text } of made) {
    const at = path.join(root, file);
    if (!fs.existsSync(at) || (await Bun.file(at).text()) !== text)
      found.push(
        `${file} differs from its source src/${file}. Edit the source and run \`just generate\`.`,
      );
  }
  const known = new Set(made.map((p) => p.file));
  for (const rel of walk(path.join(root, "wiki")))
    if (!known.has(`wiki/${rel}`))
      found.push(`wiki/${rel} has no source in src/wiki/.`);
  return found;
};
