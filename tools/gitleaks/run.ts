#!/usr/bin/env bun
// Usage: just gitleaks-rules [--fetch|--upstream]
// One JSON string, not rows: the mod loader takes no `.json` import and rows exceed the file limit.

import { join } from "node:path";
import { file as bunFile, write as bunWrite, CryptoHasher } from "bun";
import type { Rules } from "../../plugins/claudetto/src/shared/secrets/gitleaks/data.ts";
import { build } from "./build.ts";

const REF = "v8.30.1";

const RAW = "https://raw.githubusercontent.com/gitleaks/gitleaks";
const LATEST = "https://github.com/gitleaks/gitleaks/releases/latest";
const CONFIG_PATH = "docs/keep/gitleaks/gitleaks.toml";
const LICENSE_PATH = "docs/keep/gitleaks/LICENSE";
const MODULE_PATH = "plugins/claudetto/src/shared/secrets/gitleaks/rules.ts";

const ROOT = join(import.meta.dir, "../..");
const read = (path: string): Promise<string> =>
	bunFile(join(ROOT, path)).text();

const digest = (text: string): string =>
	new CryptoHasher("sha256").update(text).digest("hex");

const get = async (url: string): Promise<string> => {
	// The GitHub API answers 403 to a request that names no agent, so every request names this tool.
	const reply = await fetch(url, { headers: { "user-agent": "claudetto" } });
	if (!reply.ok) {
		throw new Error(`${url} answered ${reply.status}`);
	}
	return await reply.text();
};

const rawUrl = (ref: string, path: string): string => `${RAW}/${ref}/${path}`;

/** Escapes non-ASCII (an invisible character hides in source) and `$` (so `${` stays out of the literal). */
const ESCAPE = /[^\x20-\x7e]|\$/g;

const ascii = (text: string): string =>
	text.replace(ESCAPE, (char) => {
		const code = char.codePointAt(0) ?? 0;
		return `\\u${code.toString(16).padStart(4, "0")}`;
	});

const comment = (text: string): string =>
	text
		.trimEnd()
		.split("\n")
		.map((line) => (line === "" ? "//" : `// ${line}`))
		.join("\n");

const render = (rules: Rules, license: string): string =>
	`// Generated by \`just gitleaks-rules\`. Do not edit: an edit fails \`bun tools/gitleaks/run.ts --check\`,
// which regenerates this file in memory and compares it byte for byte.
//
// Source: ${rawUrl(rules.ref, "config/gitleaks.toml")}
// SHA-256: ${rules.sha256}
// Rules: ${rules.rules.length} kept, ${rules.dropped.length} left out, which \`gitleaksDropped\` lists with the reason.
//
// The rules are data of the Gitleaks project, used under its licence, which follows in full.
//
${comment(license)}

/** The rule data of \`data.ts\`, as JSON, parsed once at load. */
export const GITLEAKS_RULES_JSON = ${ascii(JSON.stringify(JSON.stringify(rules)))};
`;

const generate = async (): Promise<{ text: string; rules: Rules }> => {
	const [toml, license] = await Promise.all([
		read(CONFIG_PATH),
		read(LICENSE_PATH),
	]);
	const rules = build(toml, REF, digest(toml));
	return { text: render(rules, license), rules };
};

const fetchConfig = async (ref: string): Promise<void> => {
	const [toml, license] = await Promise.all([
		get(rawUrl(ref, "config/gitleaks.toml")),
		get(rawUrl(ref, "LICENSE")),
	]);
	await Promise.all([
		bunWrite(join(ROOT, CONFIG_PATH), toml),
		bunWrite(join(ROOT, LICENSE_PATH), license),
	]);
	console.info(`${CONFIG_PATH}: ${ref}, sha256 ${digest(toml)}`);
};

const write = async (): Promise<void> => {
	const { text, rules } = await generate();
	await bunWrite(join(ROOT, MODULE_PATH), text);
	console.info(
		`${MODULE_PATH}: ${rules.rules.length} rules, ${rules.dropped.length} left out`,
	);
};

const check = async (): Promise<void> => {
	const { text: want } = await generate();
	const have = await read(MODULE_PATH).catch(() => "");
	if (want === have) {
		return;
	}
	console.error(
		`${MODULE_PATH}: does not match the vendored ${CONFIG_PATH} under ref ${REF}. Run \`just gitleaks-rules\`.`,
	);
	process.exitCode = 1;
};

/** Read from the redirect, because the REST API refuses an unauthenticated run past its hourly limit. */
const newestTag = async (): Promise<string | undefined> => {
	const reply = await fetch(LATEST, {
		redirect: "manual",
		headers: { "user-agent": "claudetto" },
	});
	const tag = reply.headers.get("location")?.split("/tag/").at(-1);
	if (tag === undefined || tag === "") {
		console.info(
			`the newest tag is unknown: ${LATEST} answered ${reply.status}`,
		);
		return undefined;
	}
	return tag;
};

const upstream = async (): Promise<void> => {
	const local = digest(await read(CONFIG_PATH));
	const [pinned, latest] = await Promise.all([
		get(rawUrl(REF, "config/gitleaks.toml")),
		newestTag(),
	]);
	console.info(`vendored  ${REF}  ${local}`);
	console.info(`original  ${REF}  ${digest(pinned)}`);
	if (digest(pinned) !== local) {
		console.error(
			`${CONFIG_PATH}: differs from the original at ${REF}. Run \`just gitleaks-rules --fetch\`.`,
		);
		process.exitCode = 1;
		return;
	}
	if (latest === undefined || latest === REF) {
		return;
	}
	const newest = digest(await get(rawUrl(latest, "config/gitleaks.toml")));
	console.info(`newest    ${latest}  ${newest}`);
	if (newest !== local) {
		console.info(
			`An update is out. Run \`just gitleaks-rules --fetch --ref ${latest}\`, then set REF in tools/gitleaks/run.ts.`,
		);
	}
};

if (import.meta.main) {
	const args = process.argv.slice(2);
	const ref = args.includes("--ref") ? args[args.indexOf("--ref") + 1] : REF;
	if (args.includes("--check")) {
		await check();
	} else if (args.includes("--upstream")) {
		await upstream();
	} else {
		if (args.includes("--fetch")) {
			await fetchConfig(ref ?? REF);
		}
		await write();
	}
}
